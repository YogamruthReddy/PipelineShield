"use client";

import React, { ChangeEvent, useRef, useState } from "react";
import { EvaluationResult } from "@/types/dashboard";
import { VerdictBadge } from "../VerdictBadge";
import { ViewHeader } from "../common/ViewHeader";
import { CopyButton } from "../common/CopyButton";
import {
  FileText,
  Download,
  Upload,
  Printer,
  AlertCircle,
  Database,
  Radio,
} from "lucide-react";

interface ReportsViewProps {
  report: EvaluationResult;
  isDemoActive: boolean;
  onFileUpload: (e: ChangeEvent<HTMLInputElement>) => void;
  uploadError: string | null;
  customFileName: string;
}

export function ReportsView({
  report,
  isDemoActive,
  onFileUpload,
  uploadError,
  customFileName,
}: ReportsViewProps) {
  const fileInputRef = useRef<HTMLInputElement>(null);
  const [activeTab, setActiveTab] = useState<"json" | "markdown">("json");

  const handleDownloadJson = () => {
    const jsonString = `data:text/json;charset=utf-8,${encodeURIComponent(
      JSON.stringify(report, null, 2)
    )}`;
    const downloadAnchor = document.createElement("a");
    downloadAnchor.setAttribute("href", jsonString);
    downloadAnchor.setAttribute(
      "download",
      `pipelineshield-report-${new Date().toISOString().replace(/[:.]/g, "-")}.json`
    );
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();
  };

  const getMarkdownContent = () => {
    const lines = [
      `# 🛡️ PipelineShield Security Assessment Report`,
      ``,
      `**Evaluated At**: \`${report.evaluated_at || new Date().toISOString()}\`  `,
      `**Decision**: **${report.decision}**  `,
      ``,
      `## Summary`,
      `- Total Findings: ${report.summary?.total_findings ?? 0}`,
      `- Blocking Violations: ${report.summary?.blocking_count ?? 0}`,
      `- Advisory Warnings: ${report.summary?.warning_count ?? 0}`,
      `- Exempted Findings: ${report.summary?.exempted ?? 0}`,
      ``,
      `## Decision Reasons`,
      ...(report.reasons || []).map((r) => `- ${r}`),
      ``,
      `## Findings Breakdown`,
      `| Severity | ID | Title | Scanner | Path |`,
      `| --- | --- | --- | --- | --- |`,
      ...(report.findings || report.blocking_findings || []).map(
        (f) =>
          `| ${f.severity} | \`${f.id}\` | ${f.title} | \`${f.scanner}\` | \`${f.file_path || "-"}\` |`
      ),
    ];
    return lines.join("\n");
  };

  const handleDownloadMarkdown = () => {
    const mdString = `data:text/markdown;charset=utf-8,${encodeURIComponent(getMarkdownContent())}`;
    const downloadAnchor = document.createElement("a");
    downloadAnchor.setAttribute("href", mdString);
    downloadAnchor.setAttribute(
      "download",
      `pipelineshield-summary-${new Date().toISOString().replace(/[:.]/g, "-")}.md`
    );
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();
  };

  const jsonContent = JSON.stringify(report, null, 2);
  const markdownContent = getMarkdownContent();

  return (
    <div className="space-y-6">
      {/* Page Header */}
      <ViewHeader
        title="Security Audit Reports & Exports"
        isPresentationTitle={true}
        editorialIntro="Official compliance audit summaries and cryptographic gate artifacts."
        description="Download schema-compliant JSON evaluation summaries, Markdown PR annotations, and formatted audit PDFs."
        icon={<FileText className="w-5 h-5 text-teal-600 dark:text-teal-400" />}
        badge={<VerdictBadge decision={report.decision} size="sm" />}
      />

      {/* Overview Metadata Card */}
      <div className="bg-white dark:bg-[#111827] rounded-xl border border-slate-200 dark:border-slate-800 p-5 shadow-xs space-y-4 transition-colors">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-slate-100 dark:border-slate-800 pb-3">
          <div className="space-y-0.5">
            <h2 className="text-sm font-bold text-slate-900 dark:text-slate-100">
              Active Assessment Footprint
            </h2>
            <p className="text-xs text-slate-500 dark:text-slate-400">
              Canonical audit summary generated by the PipelineShield evaluation engine.
            </p>
          </div>
          <div className="flex items-center space-x-2">
            {isDemoActive ? (
              <span className="inline-flex items-center gap-1.5 text-xs font-mono font-semibold px-2.5 py-1 rounded-full bg-amber-50 dark:bg-amber-950/60 text-amber-700 dark:text-amber-300 border border-amber-300 dark:border-amber-800">
                <Radio className="w-3 h-3 text-amber-500 animate-pulse" />
                DEMO EVALUATION
              </span>
            ) : (
              <span className="inline-flex items-center gap-1.5 text-xs font-mono font-semibold px-2.5 py-1 rounded-full bg-teal-50 dark:bg-teal-950/60 text-teal-700 dark:text-teal-300 border border-teal-300 dark:border-teal-800">
                <Database className="w-3 h-3 text-teal-600" />
                INGESTED: {customFileName || "Custom Report"}
              </span>
            )}
          </div>
        </div>

        {/* Action Buttons */}
        <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
          <button
            type="button"
            onClick={handleDownloadJson}
            className="p-3.5 rounded-xl border border-slate-200 dark:border-slate-800 bg-slate-50/50 dark:bg-slate-800/40 hover:bg-white dark:hover:bg-slate-800 transition-all text-left cursor-pointer shadow-2xs group"
          >
            <div className="flex items-center justify-between">
              <span className="text-xs font-semibold text-slate-900 dark:text-slate-100">
                JSON Evaluation Report
              </span>
              <Download className="w-4 h-4 text-teal-600 dark:text-teal-400 group-hover:translate-y-0.5 transition-transform" />
            </div>
            <p className="text-xs text-slate-500 dark:text-slate-400 mt-1">
              Full machine-readable schema for CI/CD automation and artifact storage.
            </p>
          </button>

          <button
            type="button"
            onClick={handleDownloadMarkdown}
            className="p-3.5 rounded-xl border border-slate-200 dark:border-slate-800 bg-slate-50/50 dark:bg-slate-800/40 hover:bg-white dark:hover:bg-slate-800 transition-all text-left cursor-pointer shadow-2xs group"
          >
            <div className="flex items-center justify-between">
              <span className="text-xs font-semibold text-slate-900 dark:text-slate-100">
                Markdown Summary
              </span>
              <Download className="w-4 h-4 text-teal-600 dark:text-teal-400 group-hover:translate-y-0.5 transition-transform" />
            </div>
            <p className="text-xs text-slate-500 dark:text-slate-400 mt-1">
              Formatted markdown table ready to paste into GitHub PR comments.
            </p>
          </button>

          <button
            type="button"
            onClick={() => window.print()}
            className="p-3.5 rounded-xl border border-slate-200 dark:border-slate-800 bg-slate-50/50 dark:bg-slate-800/40 hover:bg-white dark:hover:bg-slate-800 transition-all text-left cursor-pointer shadow-2xs group"
          >
            <div className="flex items-center justify-between">
              <span className="text-xs font-semibold text-slate-900 dark:text-slate-100">
                Print / Save PDF
              </span>
              <Printer className="w-4 h-4 text-slate-500 dark:text-slate-400 group-hover:scale-105 transition-transform" />
            </div>
            <p className="text-xs text-slate-500 dark:text-slate-400 mt-1">
              Formal audit document via browser print dialogue with clean print layout.
            </p>
          </button>
        </div>
      </div>

      {/* Upload Custom Report Zone */}
      <div className="bg-white dark:bg-[#111827] rounded-xl border border-slate-200 dark:border-slate-800 p-5 shadow-xs space-y-3 transition-colors">
        <h3 className="text-sm font-semibold tracking-tight text-slate-900 dark:text-slate-100">
          Upload Custom CI/CD Evaluation Report
        </h3>
        <p className="text-xs text-slate-500 dark:text-slate-400 leading-relaxed">
          Ingest a report generated by <code className="font-mono bg-slate-100 dark:bg-slate-800 px-1 py-0.5 rounded text-teal-700 dark:text-teal-300">pipelineshield evaluate</code> or your GitHub Actions CI pipeline. The dashboard authoritatively validates required schema fields before displaying.
        </p>

        <input
          type="file"
          ref={fileInputRef}
          onChange={onFileUpload}
          accept=".json"
          className="hidden"
          aria-label="Upload custom report JSON"
        />

        <div className="flex flex-wrap items-center gap-3 pt-1">
          <button
            type="button"
            onClick={() => fileInputRef.current?.click()}
            className="inline-flex items-center space-x-2 px-4 py-2 rounded-lg bg-[#0F172A] dark:bg-slate-100 text-white dark:text-slate-900 text-xs font-bold hover:bg-slate-800 dark:hover:bg-white transition-colors cursor-pointer shadow-2xs"
          >
            <Upload className="w-4 h-4 text-teal-400 dark:text-teal-600" />
            <span>Select JSON File...</span>
          </button>
          <span className="text-xs text-slate-400 dark:text-slate-500">
            Accepts JSON with schema: decision, reasons, summary, scanner_status.
          </span>
        </div>

        {uploadError && (
          <div className="p-3.5 rounded-lg bg-red-50 dark:bg-red-950/40 border border-red-200 dark:border-red-900/60 text-xs text-red-900 dark:text-red-200 flex items-start space-x-2">
            <AlertCircle className="w-4 h-4 text-red-600 dark:text-red-400 shrink-0 mt-0.5" />
            <div className="space-y-0.5">
              <span className="font-semibold block">Schema Validation Error:</span>
              <span className="font-mono text-[11px] block">{uploadError}</span>
            </div>
          </div>
        )}
      </div>

      {/* Live Preview Tabs */}
      <div className="bg-white dark:bg-[#111827] rounded-xl border border-slate-200 dark:border-slate-800 shadow-xs overflow-hidden transition-colors">
        <div className="p-3 bg-slate-50 dark:bg-slate-800/60 border-b border-slate-200 dark:border-slate-800 flex items-center justify-between">
          <div className="flex items-center space-x-2">
            <button
              type="button"
              onClick={() => setActiveTab("json")}
              className={`px-3 py-1 rounded-md text-xs font-mono font-medium transition-colors cursor-pointer ${
                activeTab === "json"
                  ? "bg-white dark:bg-slate-900 text-slate-900 dark:text-slate-100 shadow-2xs font-bold"
                  : "text-slate-500 dark:text-slate-400 hover:text-slate-900"
              }`}
            >
              JSON Contract Preview
            </button>
            <button
              type="button"
              onClick={() => setActiveTab("markdown")}
              className={`px-3 py-1 rounded-md text-xs font-mono font-medium transition-colors cursor-pointer ${
                activeTab === "markdown"
                  ? "bg-white dark:bg-slate-900 text-slate-900 dark:text-slate-100 shadow-2xs font-bold"
                  : "text-slate-500 dark:text-slate-400 hover:text-slate-900"
              }`}
            >
              Markdown PR Comment Preview
            </button>
          </div>
          <CopyButton text={activeTab === "json" ? jsonContent : markdownContent} label="Copy Content" />
        </div>

        <div className="p-4 max-h-96 overflow-y-auto font-mono text-xs bg-slate-950 text-slate-200">
          <pre className="whitespace-pre-wrap break-all leading-relaxed">
            {activeTab === "json" ? jsonContent : markdownContent}
          </pre>
        </div>
      </div>
    </div>
  );
}
